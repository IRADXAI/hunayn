    try { return JSON.parse(t); } catch { /* repair below */ }

    // Walk the string tracking string/escape/bracket state; close what's open
    // and escape raw control characters that appear inside strings.
    let inStr = false, esc = false;
    const stack = [];
    let out = "";
    for (let i = 0; i < t.length; i++) {
      const c = t[i];
      if (esc) { out += c; esc = false; continue; }
      if (c === "\\") { out += c; esc = true; continue; }
      if (c === '"') { out += c; inStr = !inStr; continue; }
      if (inStr) {
        if (c === "\n") { out += "\\n"; continue; }
        if (c === "\r") { out += "\\r"; continue; }
        if (c === "\t") { out += "\\t"; continue; }
        out += c;
        continue;
      }
      out += c;
      if (c === "{" || c === "[") stack.push(c);
      else if (c === "}" || c === "]") stack.pop();
    }
    if (inStr) out += '"';
    // Remove a dangling comma or partial key before closing.
    out = out.replace(/,\s*$/, "").replace(/,\s*"[^"]*"?\s*:?\s*$/, "");
