// ── Lung-RADS 2022 calculator ──
// Simplified ACR Lung-RADS v2022 category assignment for the common nodule scenarios.
function lungRadsCompute({ size, comp, status, exam }) {
  // size in mm (longest average diameter). comp: solid | partsolid | ground | perifissural | atypcyst
  // status: new | growing | stable | unchanged. exam: baseline | followup
  const S = Number(size);
  const r = (cat, mgmt, note) => ({ cat, mgmt, note });

  // Perifissural / juxtapleural nodule
  if (comp === "perifissural") {
    if (S < 10) return r("2", "12-month screening LDCT", "Typical perifissural/juxtapleural nodule, < 10 mm.");
    return r("3", "6-month LDCT", "Perifissural nodule >= 10 mm; evaluate morphology.");
  }

  // Growing nodules escalate
  if (status === "growing") {
    if (comp === "solid") {
      if (S < 8) return r("3", "6-month LDCT", "Growing solid nodule < 8 mm.");
      return r("4A", "3-month LDCT; PET/CT may be considered if >= 8 mm solid component", "Growing solid nodule >= 8 mm.");
    }
    if (comp === "partsolid") return r("4B", "Diagnostic chest CT with or without contrast; PET/CT and/or tissue sampling may be considered", "Growing part-solid nodule.");
    if (comp === "ground") return r("4A", "3-month LDCT", "Growing nonsolid (ground-glass) nodule.");
  }

  // Baseline / stable assessment by composition and size
  if (comp === "solid") {
    if (S < 6) return r("2", "12-month screening LDCT", "Solid nodule < 6 mm.");
    if (S < 8) return r("3", "6-month LDCT", "Solid nodule 6 to < 8 mm at baseline.");
    if (S < 15) return r("4A", "3-month LDCT; PET/CT may be considered if >= 8 mm solid component", "Solid nodule 8 to < 15 mm.");
    return r("4B", "Diagnostic chest CT with or without contrast; PET/CT and/or tissue sampling may be considered", "Solid nodule >= 15 mm.");
  }

  if (comp === "partsolid") {
    if (S < 6) return r("2", "12-month screening LDCT", "Part-solid nodule < 6 mm total diameter.");
    // >= 6 mm: driven by solid component; without a separate solid measure, classify by total size
    if (S < 8) return r("3", "6-month LDCT", "Part-solid nodule >= 6 mm with solid component < 6 mm.");
    return r("4B", "Diagnostic chest CT with or without contrast; PET/CT and/or tissue sampling may be considered", "Part-solid nodule with solid component >= 6 mm; confirm solid component.");
  }

  if (comp === "ground") {
    if (S < 30) return r("2", "12-month screening LDCT", "Nonsolid (ground-glass) nodule < 30 mm.");
    return r("3", "6-month LDCT", "Nonsolid (ground-glass) nodule >= 30 mm.");
  }

  if (comp === "atypcyst") {
    return r("4A", "3-month LDCT", "Atypical pulmonary cyst; category depends on wall/loculation, verify morphology.");
  }

  return r("0", "Comparison to prior chest CT or additional imaging", "Incomplete; verify inputs.");
}

